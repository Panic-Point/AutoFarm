// Builds docs/chapters.md and docs/solutions.md from the game's data and
// tests/solutions.mjs, so the docs can't drift from the game.
//
//   npm run docs        rebuild both files
//
// tests/docs.test.mjs fails when the files on disk are out of date.

import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { CHAPTERS, QUESTS } from "../js/chapters.js";
import { CONTRACTS, GOLDEN } from "../js/postgame.js";
import { contractText, shopItem } from "../js/progress.js";
import { plural, questPlots } from "../js/quests.js";
import { WORDS, wordsInChapter } from "../js/words.js";
import { SOLUTIONS } from "../tests/solutions.mjs";
import {
  AFTER_FESTIVAL_CONCEPTS, AFTER_FESTIVAL_NOTE, CHAPTER_CONCEPTS, CHAPTER_NOTES, SOLUTION_NOTES, WORD_NOTES,
} from "./docs-notes.mjs";

const GENERATED = "<!-- Generated by scripts/build-docs.mjs from the game's data. Run `npm run docs` to rebuild; don't edit by hand. -->";

export const DOCS = {
  chapters: new URL("../docs/chapters.md", import.meta.url),
  solutions: new URL("../docs/solutions.md", import.meta.url),
};

function anchor(text) {
  return text.toLowerCase().replace(/[^\w\- ]/g, "").trim().replace(/ /g, "-");
}

function chapterHeading(ch) {
  return `Chapter ${ch.n}: ${ch.title}`;
}

function cell(text) {
  return String(text).replace(/\|/g, "\\|");
}

function code(text, lang = "") {
  return "```" + lang + "\n" + text.trim() + "\n```";
}

function plotsText(quest) {
  const n = questPlots(quest).length;
  return n > 1 ? `${n} test plots` : "";
}

function starsText(quest) {
  return `3 for ${plural(quest.stars.three, "tick")} or fewer, 2 for ${plural(quest.stars.two, "tick")} or fewer.`;
}

// The coding words each solution uses, found by py/words.py the same way the
// game finds them for the locks: { questId: [word, ...] }.
const FIND_WORDS = `
import ast, json, sys
sys.path.insert(0, sys.argv[1])
import plain_words, words
out = {}
for qid, files in json.load(sys.stdin).items():
    found = []
    for code in files:
        tags = {}
        tree = ast.parse(plain_words.translate(code, tags))
        found += [w for w, _ in words.find_words(tree, tags) if w not in found]
    out[qid] = found
print(json.dumps(out))
`;

let usedWords = null;
function wordsUsed(id) {
  if (!usedWords) {
    const input = Object.fromEntries(Object.entries(SOLUTIONS).map(([qid, sol]) =>
      [qid, (typeof sol === "string" ? [sol] : Object.values(sol)).map((c) => c.trim() + "\n")]));
    const pyDir = fileURLToPath(new URL("../py/", import.meta.url));
    usedWords = JSON.parse(execFileSync("python3", ["-c", FIND_WORDS, pyDir], { input: JSON.stringify(input) }));
  }
  return usedWords[id] ?? [];
}

// The words from a chapter that a quest's solution uses: what it practices.
// A quest that uses none of its chapter's words practices earlier ones.
function practices(quest, chapter) {
  const order = Object.keys(WORDS);
  const pick = (test) => [...new Set(wordsUsed(quest.id).filter(test))]
    .sort((a, b) => order.indexOf(a) - order.indexOf(b)).map((w) => WORDS[w].label).join(", ");
  const own = pick((w) => WORDS[w].chapter === chapter);
  if (own) return own;
  const earlier = pick((w) => WORDS[w].chapter > 1 && WORDS[w].chapter < chapter);
  return earlier && `earlier words: ${earlier}`;
}

// The `needs` goal: words the quest has to use, one from each group.
function mustUse(quest) {
  return (quest.goal.needs ?? []).map((group) => group.map((w) => WORDS[w].label).join(" or ")).join("; ");
}

function wordSection(id) {
  const word = WORDS[id];
  const note = WORD_NOTES[id];
  if (!note) throw new Error(`scripts/docs-notes.mjs: no WORD_NOTES entry for "${id}"`);
  const lines = [`#### ${word.label}`, "", note.text];
  if (note.forms) lines.push("", `Written as: ${note.forms.map((f) => "`" + f + "`").join(", ")}.`);
  lines.push("", code(note.example, "python"));
  return lines.join("\n");
}

function concepts(n) {
  const c = CHAPTER_CONCEPTS[n];
  if (!c) throw new Error(`scripts/docs-notes.mjs: no CHAPTER_CONCEPTS entry for chapter ${n}`);
  return c;
}

// The bold name at the start of each point: "**Loops.** ..." gives "loops".
function conceptNames(c) {
  return c.points.map((p) => {
    const m = p.match(/^\*\*(.+?)\.?\*\*/);
    if (!m) throw new Error(`scripts/docs-notes.mjs: a concept point must start with its **name.**: ${p.slice(0, 40)}`);
    const name = m[1].replace(/\.$/, "");
    return name.startsWith("Boolean") ? name : name.replace(/^\w/, (ch) => ch.toLowerCase());
  }).join(", ");
}

function conceptPoints(c) {
  return c.points.flatMap((p) => [p, ""]);
}

function questTable(chapter) {
  const rows = ["| Quest | Title | From | Goal | Practices | Must use | Notes |", "| --- | --- | --- | --- | --- | --- | --- |"];
  for (const q of chapter.quests) {
    const notes = [q.bonus && "Bonus", q.starter !== undefined && "Fix Bolt's code", plotsText(q),
      !Array.isArray(q.field) && q.field.fog && "Fog"].filter(Boolean).join(", ");
    rows.push(`| ${q.id} | ${cell(q.title)} | ${cell(q.who)} | ${cell(q.goalText)} | ${cell(practices(q, chapter.n))} | ${cell(mustUse(q))} | ${notes} |`);
  }
  return rows.join("\n");
}

export function buildChapters() {
  const out = [
    "# Chapter guide",
    "",
    GENERATED,
    "",
    "A walkthrough of each chapter of AutoFarm and what it teaches, for grown-ups helping a child, teachers, and anyone working on the game. Every chapter teaches one coding idea through short quests from a neighbor at Willow Creek Farm. For working programs, see [Quest solutions](solutions.md) (spoilers). For how quests and stars work in general, see [Game design](design.md).",
    "",
    "Each chapter has two layers. **Programming concepts** are the general ideas it teaches, the ones a child will meet again in any programming language: sequencing, loops, conditionals, variables, functions and lists. **Coding words** are how AutoFarm writes those ideas, in plain words and in Python. The game's own lessons and the Farm Book (`js/concepts.js`) teach the words to the player; this guide is for the grown-ups.",
    "",
    "A quest gives 1 star for meeting its goal, 2 stars within one tick limit and 3 within a tighter one. Bonus quests give stars but aren't needed to finish a chapter. A coding word stays locked until its chapter opens.",
    "",
    "## Chapters",
    "",
    "| # | Chapter | Neighbor | Programming concepts | Coding words | Quests | Opens with |",
    "| --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const ch of CHAPTERS) {
    const words = wordsInChapter(ch.n).map((id) => WORDS[id].label).join(", ");
    const ids = `${ch.quests[0].id} to ${ch.quests[ch.quests.length - 1].id}`;
    out.push(`| ${ch.n} | [${ch.title}](#${anchor(chapterHeading(ch))}) | ${ch.who} | ${conceptNames(concepts(ch.n))} | ${words} | ${ids} | ${ch.starsToOpen} stars |`);
  }
  out.push(`| | [After the Festival](#after-the-festival) | everyone | ${conceptNames(AFTER_FESTIVAL_CONCEPTS)} | old words on new fields | ${GOLDEN[0].id} to ${GOLDEN[GOLDEN.length - 1].id}, ${CONTRACTS[0].id} to ${CONTRACTS[CONTRACTS.length - 1].id} | finishing chapter ${CHAPTERS.length} |`);

  for (const ch of CHAPTERS) {
    const note = CHAPTER_NOTES[ch.n];
    if (!note) throw new Error(`scripts/docs-notes.mjs: no CHAPTER_NOTES entry for chapter ${ch.n}`);
    const core = ch.quests.filter((q) => !q.bonus).length;
    const opens = ch.starsToOpen === 0
      ? "Open from the start."
      : `Opens when chapter ${ch.n - 1} is finished and the player has ${ch.starsToOpen} stars.`;
    out.push(
      "",
      `## ${chapterHeading(ch)}`,
      "",
      `**${ch.who}:** "${ch.intro}"`,
      "",
      `${opens} Finishing its ${core} core quests earns the **${ch.badge}**.`,
      "",
      "### Programming concepts",
      "",
      ...conceptPoints(concepts(ch.n)),
      "### Coding words",
      "",
      ...wordsInChapter(ch.n).flatMap((id) => [wordSection(id), ""]),
      "### New on the farm",
      "",
      note,
      "",
      "### Quests",
      "",
      questTable(ch),
    );
  }

  out.push(
    "",
    "## After the Festival",
    "",
    AFTER_FESTIVAL_NOTE,
    "",
    "### Programming concepts",
    "",
    ...conceptPoints(AFTER_FESTIVAL_CONCEPTS),
    "### Golden quests",
    "",
    "| Quest | Title | From | Goal | Idea from | Practices |",
    "| --- | --- | --- | --- | --- | --- |",
    ...GOLDEN.map((q) => `| ${q.id} | ${cell(q.title)} | ${cell(q.who)} | ${cell(q.goalText)} | Chapter ${q.from}: ${CHAPTERS[q.from - 1].title} | ${cell(practices(q, q.from))} |`),
    "",
    "### The contract board",
    "",
    "| Contract | From | Order | Thank-you in the shop |",
    "| --- | --- | --- | --- |",
    ...CONTRACTS.map((c) => {
      const name = c.title ? `${c.id}: ${c.title}` : c.id;
      const needs = c.needs ? ` (needs the ${c.needs.map((id) => shopItem(id)?.name ?? id).join(", ")})` : "";
      return `| ${cell(name)} | ${cell(c.who)} | ${cell(contractText(c))}${needs} | ${cell(shopItem(c.reward)?.name ?? c.reward)} |`;
    }),
    "",
  );
  return out.join("\n");
}

function solutionCode(solution) {
  if (typeof solution === "string") return code(solution, "python");
  const { main, ...windows } = solution;
  return [
    "**main** window:", "", code(main, "python"),
    ...Object.entries(windows).flatMap(([name, text]) => ["", `**${name}** window:`, "", code(text, "python")]),
  ].join("\n");
}

export function buildSolutions() {
  const out = [
    "# Quest solutions",
    "",
    "> **⚠️ Spoilers!** This page has a working answer for every quest in the game. Each one is folded away: click **Show the solution** to open it. If you're playing, try the quest and its hints first: working it out is the fun part. Grown-ups and teachers: these are here so you can help when someone is stuck.",
    "",
    GENERATED,
    "",
    "Every program here earns 3 stars. They come from `tests/solutions.mjs`, and `npm test` runs each one with the real game and Python, so they're known to work. Plain-word code and Python can be mixed; see [Game design](design.md#plain-word-code). For what each chapter teaches, see the [Chapter guide](chapters.md). The contracts after the festival have no fixed answer, so they aren't here.",
    "",
  ];
  const groups = [
    ...CHAPTERS.map((ch) => ({ heading: chapterHeading(ch), quests: QUESTS.filter((q) => q.chapter === ch.n) })),
    { heading: "After the Festival: golden quests", quests: QUESTS.filter((q) => q.golden) },
  ];
  out.push(...groups.map((g) => `- [${g.heading}](#${anchor(g.heading)})`), "");
  for (const g of groups) {
    out.push(`## ${g.heading}`, "");
    for (const q of g.quests) {
      const solution = SOLUTIONS[q.id];
      if (solution === undefined) throw new Error(`tests/solutions.mjs: no solution for ${q.id}`);
      const note = SOLUTION_NOTES[q.id];
      if (!note) throw new Error(`scripts/docs-notes.mjs: no SOLUTION_NOTES entry for ${q.id}`);
      const tags = [q.bonus && "bonus", q.starter !== undefined && "fix Bolt's code", plotsText(q)].filter(Boolean);
      out.push(
        `### ${q.id} ${q.title}${tags.length ? ` (${tags.join(", ")})` : ""}`,
        "",
        `**Goal:** ${q.goalText}`,
        "",
        `**Stars:** ${starsText(q)}`,
        "",
        "<details>",
        "<summary>Show the solution</summary>",
        "",
        solutionCode(solution),
        "",
        `**Why it works:** ${note}`,
        "",
        "</details>",
        "",
      );
    }
  }
  return out.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(DOCS.chapters, buildChapters());
  await writeFile(DOCS.solutions, buildSolutions());
  console.log("Wrote docs/chapters.md and docs/solutions.md");
}
